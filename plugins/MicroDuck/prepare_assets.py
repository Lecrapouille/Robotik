#!/usr/bin/env python3
"""Build the asset pack of the MicroDuck plugin from microduck_rl.

Called by the Makefile of the plugin once the clone is there:

    python3 prepare_assets.py <microduck_rl> <plugin dir>

Writes the asset pack data/microduck/, and nothing else:

  - microduck.urdf and its meshes, from robot_groundcontact.xml (the open
    chain of 14 servos the walking policy was trained against; the free
    joint is dropped, RobotIK adds it);
  - walk.yaml, the contract of that policy;
  - walk.onnx, velstand.onnx from the official policy set;
  - pack.yaml, and the licenses of microduck_rl.

The worlds are written by hand in worlds/: the duck walks there.

Only the Python standard library is used.
"""

import math
import shutil
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROBOT_XML = Path("src/mjlab_microduck/robot/microduck/robot_groundcontact.xml")
SCENE_WALK = Path("src/mjlab_microduck/robot/microduck/scene_walk.xml")
# Confirmed in scripts/infer_policy.py and sim/body_server.py: the scenes
# ship 0.002, and that step cannot hold the duck. Training is 5 ms, and the
# policy runs every 4 steps (50 Hz).
PHYSICS_STEP_S = 0.005
DECIMATION = 4
# velstand: the walk that also stands still and gets back up.
POLICY_URL = (
    "https://huggingface.co/pollen-robotics/microduck-policies/resolve/main/velstand.onnx"
)
# Command ranges of the velocity task (m/s, m/s, rad/s).
MAX_COMMAND = (0.4, 0.3, 1.0)
PACK = """id: robotik.pollen
version: 1.0.0
license: CC-BY-NC-SA-4.0
source: https://github.com/pollen-robotics/microduck_rl
description: >
  Microduck (Pollen Robotics): URDF converted from the ground-contact MJCF,
  STL meshes (CC BY-NC-SA 4.0) and the velstand walking policy (Apache-2.0).
  Generated by prepare_assets.py of the MicroDuck plugin.
models:
  microduck: microduck.urdf
"""


def tokens(text: str) -> list[float]:
    return [float(part) for part in text.split()]


def quat_to_matrix(w: float, x: float, y: float, z: float) -> list[list[float]]:
    """Rotation matrix of a unit quaternion (w, x, y, z)."""
    return [
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ]


def quat_to_rpy(quat: str) -> tuple[float, float, float]:
    """MuJoCo quat (w x y z) as URDF rpy: R = Rz(yaw) Ry(pitch) Rx(roll).

    The asin formula locks when pitch is ±90° (several leg and foot meshes).
    The matrix form still picks one rpy that rebuilds the same rotation.
    """
    w, x, y, z = tokens(quat)
    norm = math.sqrt(w * w + x * x + y * y + z * z)
    if norm == 0.0:
        return (0.0, 0.0, 0.0)
    w, x, y, z = w / norm, x / norm, y / norm, z / norm
    row = quat_to_matrix(w, x, y, z)
    pitch = math.atan2(-row[2][0], math.hypot(row[0][0], row[1][0]))
    if abs(math.cos(pitch)) < 1e-8:
        # Gimbal lock: roll is free. Keep it at 0 and fold the angle into yaw.
        roll = 0.0
        yaw = math.atan2(-row[0][1], row[1][1])
    else:
        roll = math.atan2(row[2][1], row[2][2])
        yaw = math.atan2(row[1][0], row[0][0])
    return (roll, pitch, yaw)


def xyz(text: str | None, default: str = "0 0 0") -> str:
    values = tokens(text or default)
    return " ".join(f"{value:.8g}" for value in values)


def rpy_of(quat: str | None) -> str:
    if not quat:
        return "0 0 0"
    return " ".join(f"{value:.8g}" for value in quat_to_rpy(quat))


def num(text: str) -> str:
    return f"{float(text):.8g}"


def default_class(root: ET.Element, name: str) -> ET.Element:
    for default in root.iter("default"):
        if default.get("class") == name:
            return default
    sys.exit(f"MJCF has no default class '{name}'")


def actuator_class(root: ET.Element) -> str:
    actuator = root.find("actuator")
    if actuator is None or len(actuator) == 0:
        sys.exit("MJCF has no actuator")
    name = actuator[0].get("class")
    if not name:
        sys.exit("the first actuator has no class")
    return name


def copy_mesh(source: Path, meshes: Path, file_name: str) -> str:
    """Copy one STL once. Returns the URDF path relative to the URDF."""
    origin = source / file_name
    if not origin.is_file():
        sys.exit(f"missing mesh {origin}")
    meshes.mkdir(parents=True, exist_ok=True)
    target = meshes / Path(file_name).name
    if not target.is_file():
        shutil.copyfile(origin, target)
    return "meshes/" + target.name


def add_inertial(link: ET.Element, body: ET.Element) -> None:
    inertial = body.find("inertial")
    if inertial is None:
        sys.exit(f"{body.get('name')}: no inertial")
    # fullinertia is Ixx Iyy Izz Ixy Ixz Iyz, in the body frame.
    moments = tokens(inertial.get("fullinertia") or inertial.get("diaginertia") or "")
    if len(moments) == 3:
        ixx, iyy, izz, ixy, ixz, iyz = moments[0], moments[1], moments[2], 0.0, 0.0, 0.0
    elif len(moments) == 6:
        ixx, iyy, izz, ixy, ixz, iyz = moments
    else:
        sys.exit(f"{body.get('name')}: inertia is not 3 or 6 numbers")
    node = ET.SubElement(link, "inertial")
    ET.SubElement(node, "origin", xyz=xyz(inertial.get("pos")), rpy="0 0 0")
    ET.SubElement(node, "mass", value=num(inertial.get("mass")))
    ET.SubElement(
        node, "inertia",
        ixx=f"{ixx:.8g}", ixy=f"{ixy:.8g}", ixz=f"{ixz:.8g}",
        iyy=f"{iyy:.8g}", iyz=f"{iyz:.8g}", izz=f"{izz:.8g}",
    )


def add_geoms(link: ET.Element, body: ET.Element, mesh_files: dict[str, str],
              meshes: Path, source: Path, colors: dict[str, str]) -> None:
    for geom in body.findall("geom"):
        kind = geom.get("class")
        if kind == "visual":
            tag = "visual"
        elif kind == "collision":
            tag = "collision"
        else:
            # self_collision_only does not meet the floor. URDF cannot say so,
            # so those meshes stay out: as collisions they would hit the ground.
            continue
        mesh_name = geom.get("mesh")
        if geom.get("type", "sphere") != "mesh" or not mesh_name:
            sys.exit(f"{body.get('name')}: a {kind} geom is not a mesh")
        node = ET.SubElement(link, tag)
        ET.SubElement(node, "origin", xyz=xyz(geom.get("pos")), rpy=rpy_of(geom.get("quat")))
        geometry = ET.SubElement(node, "geometry")
        ET.SubElement(geometry, "mesh", filename=copy_mesh(source, meshes, mesh_files[mesh_name]))
        if tag == "visual":
            color = colors.get(geom.get("material", ""))
            if color:
                ET.SubElement(node, "material", name=geom.get("material"))
                # The material element itself is added once on the robot.


def add_joint(robot: ET.Element, body: ET.Element, parent: str, effort: float) -> str:
    hinges = [joint for joint in body.findall("joint") if joint.get("type") == "hinge"]
    if len(hinges) != 1:
        sys.exit(f"{body.get('name')}: expected one hinge, found {len(hinges)}")
    hinge = hinges[0]
    name = hinge.get("name")
    if not name:
        sys.exit(f"{body.get('name')}: hinge without a name")
    joint = ET.SubElement(robot, "joint", name=name, type="revolute")
    ET.SubElement(joint, "parent", link=parent)
    ET.SubElement(joint, "child", link=body.get("name"))
    ET.SubElement(joint, "origin", xyz=xyz(body.get("pos")), rpy=rpy_of(body.get("quat")))
    ET.SubElement(joint, "axis", xyz=hinge.get("axis", "0 0 1"))
    lower, upper = tokens(hinge.get("range", "-3.14 3.14"))
    ET.SubElement(
        joint, "limit",
        lower=f"{lower:.8g}", upper=f"{upper:.8g}",
        effort=f"{effort:.8g}", velocity="20",
    )
    return name


def convert_body(robot: ET.Element, body: ET.Element, parent: str | None,
                 mesh_files: dict[str, str], meshes: Path, source: Path,
                 colors: dict[str, str], effort: float, joints: list[str]) -> None:
    link = ET.SubElement(robot, "link", name=body.get("name"))
    add_inertial(link, body)
    add_geoms(link, body, mesh_files, meshes, source, colors)
    if parent is not None:
        joints.append(add_joint(robot, body, parent, effort))
    elif body.find("freejoint") is None:
        sys.exit(f"{body.get('name')}: the root body has no free joint")
    for child in body.findall("body"):
        convert_body(robot, child, body.get("name"), mesh_files, meshes, source,
                     colors, effort, joints)


def stand_pose(scene: ET.Element) -> tuple[list[float], list[float]]:
    """Trunk position (m) and the 14 joint angles of the STAND keyframe."""
    for key in scene.iter("key"):
        if key.get("name") == "STAND":
            qpos = tokens(key.get("qpos") or "")
            if len(qpos) < 7:
                sys.exit("STAND keyframe has no free-joint pose")
            return qpos[0:3], qpos[7:]
    sys.exit("scene_walk.xml has no STAND key")


def flow(values: list[float]) -> str:
    return "[" + ", ".join(f"{value:.8g}" for value in values) + "]"


def names(values: list[str]) -> str:
    return "[" + ", ".join(values) + "]"


def write_contract(path: Path, joint_names: list[str], home: list[float],
                   kp: float, effort: float, damping: float, armature: float) -> None:
    count = len(joint_names)
    if len(home) != count:
        sys.exit(f"STAND has {len(home)} joints, the actuators {count}")
    lines = [
        "# Contract of walk.onnx (velstand), generated by prepare_assets.py.",
        "# kp is the position gain of the MJCF; the viscous term is damping,",
        "# not a derivative gain (the position actuator kv is 0).",
        "# physics_step and decimation: 5 ms, policy every 4 steps, 50 Hz.",
        "walk:",
        f"  joints: {names(joint_names)}",
        f"  kp: {flow([kp] * count)}",
        f"  kd: {flow([0.0] * count)}",
        f"  damping: {flow([damping] * count)}",
        f"  default_angle: {flow(home)}",
        f"  action_scale: {flow([1.0] * count)}",
        f"  torque_limit: {flow([effort] * count)}",
        f"  armature: {flow([armature] * count)}",
        f"  decimation: {DECIMATION}",
        f"  physics_step: {PHYSICS_STEP_S}",
        "  observations: 61",
        f"  max_command: [{MAX_COMMAND[0]}, {MAX_COMMAND[1]}, {MAX_COMMAND[2]}]",
    ]
    path.write_text("\n".join(lines) + "\n")


def download_policy(path: Path) -> None:
    if path.is_file() and path.stat().st_size > 1000:
        return
    print(f"downloading {POLICY_URL}", file=sys.stderr)
    urllib.request.urlretrieve(POLICY_URL, path)


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source_root = Path(sys.argv[1])
    plugin = Path(sys.argv[2])
    robot_xml = source_root / ROBOT_XML
    if not robot_xml.is_file():
        sys.exit(f"missing {robot_xml}")
    root = ET.parse(robot_xml).getroot()
    klass = actuator_class(root)
    defaults = default_class(root, klass)
    position = defaults.find("position")
    joint = defaults.find("joint")
    if position is None or joint is None:
        sys.exit(f"class {klass} has no position or joint")
    kp = float(position.get("kp"))
    kv = float(position.get("kv", "0"))
    if kv != 0.0:
        sys.exit(f"class {klass}: kv is {kv}, the contract assumes 0")
    effort = abs(tokens(position.get("forcerange"))[0])
    damping = float(joint.get("damping"))
    armature = float(joint.get("armature"))

    mesh_files = {}
    for mesh in root.iter("mesh"):
        file_name = mesh.get("file")
        mesh_files[Path(file_name).stem] = file_name
    colors = {
        node.get("name"): node.get("rgba")
        for node in root.iter("material")
        if node.get("rgba")
    }

    output = plugin / "data" / "microduck"
    meshes = output / "meshes"
    if meshes.is_dir():
        shutil.rmtree(meshes)
    output.mkdir(parents=True, exist_ok=True)

    robot = ET.Element("robot", name="microduck")
    for name, color in sorted(colors.items()):
        red, green, blue, *_ = tokens(color)
        material = ET.SubElement(robot, "material", name=name)
        ET.SubElement(material, "color", rgba=f"{red:.8g} {green:.8g} {blue:.8g} 1")
    mesh_dir = source_root / ROBOT_XML.parent / root.find("compiler").get("meshdir", "assets")
    world = root.find("worldbody")
    bodies = world.findall("body")
    if len(bodies) != 1:
        sys.exit(f"expected one root body, found {len(bodies)}")
    joint_names: list[str] = []
    convert_body(robot, bodies[0], None, mesh_files, meshes, mesh_dir, colors,
                 effort, joint_names)
    actuators = [node.get("joint") for node in root.find("actuator")]
    if actuators != joint_names:
        sys.exit("joint order of the tree and of the actuators differ")

    tree = ET.ElementTree(robot)
    ET.indent(tree)
    tree.write(output / "microduck.urdf", encoding="utf-8", xml_declaration=True)

    _, home = stand_pose(ET.parse(source_root / SCENE_WALK).getroot())
    write_contract(output / "walk.yaml", joint_names, home, kp, effort, damping, armature)
    download_policy(output / "walk.onnx")
    for notice in ("LICENSE", "LICENSE-MODELS.md"):
        shutil.copyfile(source_root / notice, output / notice)

    (output / "pack.yaml").write_text(PACK)
    print(f"microduck: {len(joint_names)} joints -> {output}", file=sys.stderr)


if __name__ == "__main__":
    main()
